import sqlite3 
import pandas as pd
import matplotlib.pyplot as plt



#Connect to database 
conn = sqlite3.connect("/home/lilly/Documents/python-assignment12/lesson.db")


#SQL 
query = """
SELECT last_name, SUM(price * quantity) AS revenue 
FROM employees e 
JOIN orders o ON e.employee_id = o.employee_id 
JOIN line_items l ON o.order_id = l.order_id 
JOIN products p ON l.product_id = p.product_id 
GROUP BY e.employee_id;
"""

#Load into DataFrame 
employee_results = pd.read_sql_query(query, conn)
conn.close()

print(employee_results)


#Plot
employee_results.plot(
    kind="bar",
    x="last_name",
    y="revenue",
    color="blue",
    figsize=(10, 6),
    rot=0
)
plt.title("Revenue Generated by Employees")
plt.xlabel("Employee Last Name")
plt.ylabel("Revenue")
plt.tight_layout()
plt.savefig('employee_revenue.png', dpi=150)
plt.show()


